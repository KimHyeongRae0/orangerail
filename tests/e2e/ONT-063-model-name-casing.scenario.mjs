/**
 * ONT-063 e2e driver — what was typed is resolved; what is recorded is scanned.
 *
 * Drives the SHIPPED CLI (packages/cli/dist/main.js) over the ont-063 fixture
 * (a Prisma SQLite source: `Customer` -> `Order`, plus a `Payment` table an
 * operator reading `psql` would type as `payment`).
 *
 *   Phase 1 (AC-1/AC-2): `init --exclude payment` succeeds, generates nothing
 *     for the table, and records `Payment` — the SCANNED name — in
 *     `orangerail.governance.json`. The very next `orangerail sync` is green and
 *     says `info: Payment is excluded`. That last assertion is the one that
 *     catches the trap: a lenient comparison recording the typed string would
 *     pass every unit test and leave a committed deny-list reading `payment`,
 *     which `splitExclusions` compares exactly and never matches — the ONT-059
 *     defect back again, behind a file that looks right.
 *   Phase 2 (AC-3): `--models customer,order` generates the same bytes as
 *     `--models Customer,Order` — every generated path and its content.
 *   Phase 3 (AC-4/AC-5/AC-6): a name matching nothing even ignoring case keeps
 *     the existing refusal; a plural or a prefix is NOT a match; the same model
 *     in both flags in different casings is still contradictory; and a schema
 *     declaring `Order` AND `order` refuses rather than picking one. None of
 *     them writes a config.
 *   Phase 4: the same resolution on `orangerail sync --exclude`, which is the
 *     command whose own report tells an operator to type a model name.
 *
 * RED (pre-implementation): phase 1 fails immediately — `init --exclude payment`
 * exits 1 with `unknown model "payment" in --exclude`.
 *
 * No database is needed anywhere: every claim is read off generated bytes, the
 * recorded baseline, and CLI exit codes.
 */
import { spawnSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CLI = join(ROOT, 'packages', 'cli', 'dist', 'main.js');
const FIXTURE = join(ROOT, 'tests', 'e2e', 'fixtures', 'ont-063');
const SCRATCH = join(ROOT, '.docs', 'scratch');

const GOVERNANCE_FILE = 'orangerail.governance.json';

/** The scanned name of the table this scenario refuses. */
const SCANNED = 'Payment';

/** What an operator reading their database types instead. */
const TYPED = 'payment';

const fail = ({ message }) => {
  console.error(`ONT-063 e2e FAIL: ${message}`);
  process.exit(1);
};

const assert = ({ ok, message }) => {
  if (!ok) {
    fail({ message });
  }
};

/** Runs an `orangerail` CLI command to completion inside a run dir. */
const runCli = ({ args, cwd }) => {
  const res = spawnSync('node', [CLI, ...args], {
    cwd,
    env: process.env,
    encoding: 'utf8',
    timeout: 60_000,
  });

  return { status: res.status, stdout: res.stdout ?? '', stderr: res.stderr ?? '' };
};

/** Copy the fixture repo into a clean scratch run dir. */
const prepareRunDir = ({ name }) => {
  const dir = join(SCRATCH, `ont-063-${name}`);

  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  cpSync(FIXTURE, dir, { recursive: true });

  return dir;
};

const readBaseline = ({ runDir }) =>
  JSON.parse(readFileSync(join(runDir, GOVERNANCE_FILE), 'utf8'));

/** Every generated ontology file, name and content, for a byte comparison. */
const ontology = ({ runDir }) => {
  const dir = join(runDir, 'ontology');

  return readdirSync(dir)
    .sort()
    .map((name) => `=== ${name}\n${readFileSync(join(dir, name), 'utf8')}`)
    .join('\n');
};

/** Append a model whose name collides with an existing one only in case. */
const addCaseTwin = ({ runDir }) => {
  const path = join(runDir, 'prisma', 'schema.prisma');

  writeFileSync(
    path,
    `${readFileSync(path, 'utf8')}
model order {
  id String @id
}
`,
    'utf8',
  );
};

/** `init` with `--yes` and no studio/docs handoff — this scenario reads files, not servers. */
const initFlags = ({ extra }) => [
  'init',
  '--yes',
  '--no-docs',
  '--no-studio',
  '--no-open',
  ...extra,
];

// ---------------------------------------------------------------------------
// Phase 1 — the typed name works, and the scanned name is what is recorded
// ---------------------------------------------------------------------------

const phase1 = () => {
  console.log('── phase 1: --exclude payment records Payment, and sync goes green ──');

  const runDir = prepareRunDir({ name: 'typed' });

  const init = runCli({ args: initFlags({ extra: [`--exclude=${TYPED}`] }), cwd: runDir });

  assert({
    ok: init.status === 0,
    message: `init --exclude ${TYPED} exited ${init.status}:\n${init.stdout}\n${init.stderr}`,
  });

  // Nothing was generated for the refused table — not the object, not one action.
  assert({
    ok: !existsSync(join(runDir, 'ontology', `${SCANNED}.mjs`)),
    message: `ontology/${SCANNED}.mjs was generated for a model that was refused`,
  });
  for (const op of ['create', 'update', 'delete']) {
    assert({
      ok: !existsSync(join(runDir, 'ontology', `${op}${SCANNED}.mjs`)),
      message: `ontology/${op}${SCANNED}.mjs was generated for a model that was refused`,
    });
  }
  assert({
    ok: existsSync(join(runDir, 'ontology', 'Customer.mjs')),
    message: 'the kept models were not generated',
  });

  // THE ASSERTION THIS TICKET IS ABOUT: the file holds the scanned spelling.
  const baseline = readBaseline({ runDir });

  assert({
    ok: JSON.stringify(baseline.excluded) === JSON.stringify([SCANNED]),
    message: `${GOVERNANCE_FILE} records excluded ${JSON.stringify(baseline.excluded)}, not ["${SCANNED}"]`,
  });

  // And the summary names what it recorded, not what was typed.
  assert({
    ok: init.stdout.includes(`refused 1 model(s) — ${SCANNED}`),
    message: `the init summary does not name the refusal by its scanned name:\n${init.stdout}`,
  });

  // THE DEFECT A LENIENT COMPARISON WOULD LEAVE: `excluded.has(name)` is exact,
  // so a recorded "payment" would re-propose the table here, forever.
  const sync = runCli({ args: ['sync'], cwd: runDir });

  assert({
    ok: sync.status === 0,
    message: `sync on a project narrowed by the typed casing exited ${sync.status}:\n${sync.stdout}\n${sync.stderr}`,
  });
  assert({
    ok: !sync.stdout.includes('proposal:'),
    message: `sync still proposes the refused model:\n${sync.stdout}`,
  });
  assert({
    ok: sync.stdout.includes(`info: ${SCANNED} is excluded, as recorded in ${GOVERNANCE_FILE}`),
    message: `sync does not report the refusal under its scanned name:\n${sync.stdout}`,
  });
  assert({
    ok: !sync.stdout.includes('matches nothing in your sources'),
    message: `the recorded name matches nothing — it was recorded as typed:\n${sync.stdout}`,
  });

  // Byte-identical to typing the scanned name in the first place (AC-1).
  const exactDir = prepareRunDir({ name: 'exact' });

  runCli({ args: initFlags({ extra: [`--exclude=${SCANNED}`] }), cwd: exactDir });

  assert({
    ok: ontology({ runDir }) === ontology({ runDir: exactDir }),
    message: 'the generated ontology differs between the typed and the scanned casing',
  });
  assert({
    ok:
      readFileSync(join(runDir, GOVERNANCE_FILE), 'utf8') ===
      readFileSync(join(exactDir, GOVERNANCE_FILE), 'utf8'),
    message: `${GOVERNANCE_FILE} differs between the typed and the scanned casing`,
  });
};

// ---------------------------------------------------------------------------
// Phase 2 — --models resolves the same way, and moves no filename
// ---------------------------------------------------------------------------

const phase2 = () => {
  console.log('── phase 2: --models resolves too, and the filenames do not move ──');

  const typedDir = prepareRunDir({ name: 'models-typed' });
  const exactDir = prepareRunDir({ name: 'models-exact' });

  const typed = runCli({
    args: initFlags({ extra: ['--models=customer,order', `--exclude=${TYPED}`] }),
    cwd: typedDir,
  });

  assert({
    ok: typed.status === 0,
    message: `init --models in the typed casing exited ${typed.status}:\n${typed.stdout}\n${typed.stderr}`,
  });

  runCli({
    args: initFlags({ extra: ['--models=Customer,Order', `--exclude=${SCANNED}`] }),
    cwd: exactDir,
  });

  assert({
    ok: existsSync(join(typedDir, 'ontology', 'Customer.mjs')),
    message: '--models customer did not generate ontology/Customer.mjs',
  });
  assert({
    ok: ontology({ runDir: typedDir }) === ontology({ runDir: exactDir }),
    message: 'the casing typed into --models changed the generated file set',
  });
};

// ---------------------------------------------------------------------------
// Phase 3 — the refusals that survive, and the one that is new
// ---------------------------------------------------------------------------

const phase3 = () => {
  console.log('── phase 3: what is still refused ──');

  // AC-4: a name matching nothing even ignoring case, and the near-misses that
  // must NOT be rescued by a prefix or plural rule.
  for (const near of ['paymnet', 'payments', 'pay']) {
    const dir = prepareRunDir({ name: `unknown-${near}` });
    const run = runCli({ args: initFlags({ extra: [`--exclude=${near}`] }), cwd: dir });
    const output = `${run.stdout}${run.stderr}`;

    assert({
      ok: run.status !== 0 && output.includes(`unknown model "${near}" in --exclude`),
      message: `--exclude ${near} was accepted (exit ${run.status}):\n${output}`,
    });
    assert({
      ok: output.includes('expected one of Customer, Order, Payment'),
      message: `the refusal for "${near}" stopped naming the valid set:\n${output}`,
    });
    assert({
      ok: !existsSync(join(dir, 'orangerail.config.mjs')),
      message: `a refused init still wrote a config for "${near}"`,
    });
  }

  // AC-5: the both-flags check runs on resolved names.
  const bothDir = prepareRunDir({ name: 'both' });
  const both = runCli({
    args: initFlags({ extra: [`--models=${SCANNED}`, `--exclude=${TYPED}`] }),
    cwd: bothDir,
  });

  assert({
    ok:
      both.status !== 0 &&
      `${both.stdout}${both.stderr}`.includes(
        `"${SCANNED}" appears in both --models and --exclude`,
      ),
    message: `differing casing smuggled one model into both flags (exit ${both.status}):\n${both.stdout}\n${both.stderr}`,
  });
  assert({
    ok: !existsSync(join(bothDir, 'orangerail.config.mjs')),
    message: 'a contradictory init still wrote a config',
  });

  // The same model named twice in two casings is ONE model, so the "names every
  // scanned model" guard must not fire on a two-of-three selection.
  const twiceDir = prepareRunDir({ name: 'twice' });
  const twice = runCli({
    args: initFlags({ extra: ['--exclude=PAYMENT,payment'] }),
    cwd: twiceDir,
  });

  assert({
    ok: twice.status === 0,
    message: `--exclude PAYMENT,payment was refused (exit ${twice.status}):\n${twice.stdout}\n${twice.stderr}`,
  });
  assert({
    ok: JSON.stringify(readBaseline({ runDir: twiceDir }).excluded) === JSON.stringify([SCANNED]),
    message: `the same model named twice was recorded as ${JSON.stringify(readBaseline({ runDir: twiceDir }).excluded)}`,
  });

  // AC-6: two models whose source names differ only in case. The allocator has
  // already renamed the second to `order_2`, so nothing about the emitted names
  // says they collide — and resolving `order` to `Order` would refuse the wrong
  // table while leaving the one the operator meant reachable.
  const twinDir = prepareRunDir({ name: 'twin' });
  addCaseTwin({ runDir: twinDir });

  const twin = runCli({ args: initFlags({ extra: ['--exclude=order'] }), cwd: twinDir });
  const twinOutput = `${twin.stdout}${twin.stderr}`;

  assert({
    ok: twin.status !== 0 && twinOutput.includes('ambiguous model "order" in --exclude'),
    message: `a name with two answers was resolved anyway (exit ${twin.status}):\n${twinOutput}`,
  });
  assert({
    ok: twinOutput.includes('it could mean Order or order_2'),
    message: `the ambiguity refusal does not name both models:\n${twinOutput}`,
  });
  assert({
    ok: !existsSync(join(twinDir, 'orangerail.config.mjs')),
    message: 'an ambiguous init still wrote a config',
  });

  // And the way through is the name the scan itself reports.
  const resolvedTwin = runCli({ args: initFlags({ extra: ['--exclude=order_2'] }), cwd: twinDir });

  assert({
    ok: resolvedTwin.status === 0,
    message: `the de-collided name was refused too (exit ${resolvedTwin.status}):\n${resolvedTwin.stdout}\n${resolvedTwin.stderr}`,
  });
  assert({
    ok: JSON.stringify(readBaseline({ runDir: twinDir }).excluded) === JSON.stringify(['order_2']),
    message: `the de-collided refusal was recorded as ${JSON.stringify(readBaseline({ runDir: twinDir }).excluded)}`,
  });
};

// ---------------------------------------------------------------------------
// Phase 4 — the same resolution on the command that hands out the advice
// ---------------------------------------------------------------------------

const phase4 = () => {
  console.log('── phase 4: sync --exclude records the scanned name too ──');

  const runDir = prepareRunDir({ name: 'sync' });

  // Narrowed with `--models`, so `Payment` is out of the ontology and genuinely
  // refusable — the state `init` closes with by naming it as unaccounted for.
  const init = runCli({
    args: initFlags({ extra: ['--models=Customer,Order'] }),
    cwd: runDir,
  });

  assert({
    ok: init.status === 0 && init.stdout.includes(`orangerail sync --exclude ${SCANNED}`),
    message: `init did not hand back the sync --exclude command (exit ${init.status}):\n${init.stdout}`,
  });

  const recorded = runCli({ args: ['sync', `--exclude=${TYPED}`], cwd: runDir });

  assert({
    ok: recorded.status === 0,
    message: `sync --exclude ${TYPED} exited ${recorded.status}:\n${recorded.stdout}\n${recorded.stderr}`,
  });
  assert({
    ok: JSON.stringify(readBaseline({ runDir }).excluded) === JSON.stringify([SCANNED]),
    message: `sync recorded ${JSON.stringify(readBaseline({ runDir }).excluded)}, not ["${SCANNED}"]`,
  });
  assert({
    ok: recorded.stdout.includes(`recorded 1 refused model(s) in ${GOVERNANCE_FILE} — ${SCANNED}`),
    message: `sync did not report the refusal by its scanned name:\n${recorded.stdout}`,
  });

  // The run after it reads only the file, and it is green and quiet.
  const next = runCli({ args: ['sync'], cwd: runDir });

  assert({
    ok: next.status === 0 && !next.stdout.includes('proposal:'),
    message: `the run after the refusal exited ${next.status}:\n${next.stdout}`,
  });
  assert({
    ok: !next.stdout.includes('matches nothing in your sources'),
    message: `sync recorded a name that matches nothing:\n${next.stdout}`,
  });

  // A near-miss is still refused, and still writes nothing.
  const near = runCli({ args: ['sync', '--exclude=payments'], cwd: runDir });

  assert({
    ok: near.status === 2 && near.stderr.includes('which your sources do not have'),
    message: `sync --exclude payments exited ${near.status}:\n${near.stdout}\n${near.stderr}`,
  });
  assert({
    ok: JSON.stringify(readBaseline({ runDir }).excluded) === JSON.stringify([SCANNED]),
    message: 'a refused sync --exclude changed the recorded deny-list',
  });
};

phase1();
phase2();
phase3();
phase4();

console.log('ONT-063 e2e: all phases passed');
