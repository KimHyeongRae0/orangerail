/**
 * ONT-059 e2e driver — a refused model stays refused, and a new one stays loud.
 *
 * Drives the SHIPPED CLI (packages/cli/dist/main.js) over the ont-059 fixture
 * (a Prisma SQLite source: `Customer` -> `Order`, plus an `ApiCredential` table
 * that must never reach the agent) and proves the defect this ticket exists for
 * is gone at the layer an operator actually experiences it — the exit code of
 * the next `orangerail sync`.
 *
 *   Phase 1 (AC-1/2/3): `init --exclude ApiCredential` writes no file for it and
 *     no action targeting it, records it in `orangerail.governance.json`, and the
 *     very next `sync` is QUIET and exits 0. Before this ticket the same project
 *     re-proposed the table and its three actions forever, so a narrowed project
 *     — the posture this product recommends — could never have a green drift
 *     check.
 *   Phase 2 (AC-4/5/7): a model added to the schema AFTER the refusal is still a
 *     loud proposal with exit 1, while the refused one stays quiet; `--accept-new`
 *     creates the new model's file and STILL NOT the refused one — the one remedy
 *     the report used to name was the one that generated it; and a recorded name
 *     dropped from the schema is reported as prunable rather than left to silence
 *     a future table of that name.
 *   Phase 3 (AC-1/6): every refusal. An unknown `--exclude` name, a name in both
 *     `--models` and `--exclude`, an `--exclude` covering every model, a
 *     `sync --exclude` with no baseline to record it in, and a `sync --exclude`
 *     naming a model the ontology already exposes. None of them writes anything.
 *
 * RED (pre-implementation): phase 1 fails immediately — `--exclude` is not a
 * flag, so `init` exits non-zero on an unknown flag; with the flag removed, the
 * follow-up `sync` proposes `ApiCredential` and exits 1.
 *
 * No database is needed anywhere: every claim is read off generated bytes, the
 * recorded baseline, and CLI exit codes.
 */
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CLI = join(ROOT, 'packages', 'cli', 'dist', 'main.js');
const FIXTURE = join(ROOT, 'tests', 'e2e', 'fixtures', 'ont-059');
const SCRATCH = join(ROOT, '.docs', 'scratch');

const GOVERNANCE_FILE = 'orangerail.governance.json';

/** The table the fixture exists to keep away from the agent. */
const REFUSED = 'ApiCredential';

const fail = ({ message }) => {
  console.error(`ONT-059 e2e FAIL: ${message}`);
  process.exit(1);
};

const assert = ({ ok, message }) => {
  if (!ok) {
    fail({ message });
  }
};

/** Runs an `orangerail` CLI command to completion inside a run dir. */
const runCli = ({ args, cwd }) => {
  const res = spawnSync('node', [CLI, ...args], {
    cwd,
    env: process.env,
    encoding: 'utf8',
    timeout: 60_000,
  });

  return { status: res.status, stdout: res.stdout ?? '', stderr: res.stderr ?? '' };
};

/** Copy the fixture repo into a clean scratch run dir. */
const prepareRunDir = ({ name }) => {
  const dir = join(SCRATCH, `ont-059-${name}`);

  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  cpSync(FIXTURE, dir, { recursive: true });

  return dir;
};

const readBaseline = ({ runDir }) =>
  JSON.parse(readFileSync(join(runDir, GOVERNANCE_FILE), 'utf8'));

const schemaPath = ({ runDir }) => join(runDir, 'prisma', 'schema.prisma');

/** Append a model to the fixture schema — a table that appears AFTER the refusal. */
const addModel = ({ runDir }) => {
  writeFileSync(
    schemaPath({ runDir }),
    `${readFileSync(schemaPath({ runDir }), 'utf8')}
model Refund {
  id     String @id
  amount Int
}
`,
    'utf8',
  );
};

/** Drop the refused table from the schema, so the recorded name matches nothing. */
const dropRefusedModel = ({ runDir }) => {
  const source = readFileSync(schemaPath({ runDir }), 'utf8');

  writeFileSync(
    schemaPath({ runDir }),
    source.replace(/model ApiCredential \{[\s\S]*?\n\}\n/, ''),
    'utf8',
  );
};

/** `init` with `--yes` and no studio/docs handoff — this scenario reads files, not servers. */
const initFlags = ({ extra }) => [
  'init',
  '--yes',
  '--no-docs',
  '--no-studio',
  '--no-open',
  ...extra,
];

// ---------------------------------------------------------------------------
// Phase 1 — a refusal is recorded, honoured, and green
// ---------------------------------------------------------------------------

const phase1 = () => {
  console.log('── phase 1: init --exclude records the refusal, and sync goes green ──');

  const runDir = prepareRunDir({ name: 'refused' });

  const init = runCli({ args: initFlags({ extra: [`--exclude=${REFUSED}`] }), cwd: runDir });

  assert({
    ok: init.status === 0,
    message: `init --exclude exited ${init.status}:\n${init.stdout}\n${init.stderr}`,
  });

  // Nothing was generated for the refused table — not the object, not one action.
  assert({
    ok: !existsSync(join(runDir, 'ontology', `${REFUSED}.mjs`)),
    message: `ontology/${REFUSED}.mjs was generated for a model that was refused`,
  });
  for (const op of ['create', 'update', 'delete']) {
    assert({
      ok: !existsSync(join(runDir, 'ontology', `${op}${REFUSED}.mjs`)),
      message: `ontology/${op}${REFUSED}.mjs was generated for a model that was refused`,
    });
  }
  assert({
    ok: existsSync(join(runDir, 'ontology', 'Customer.mjs')),
    message: 'the kept models were not generated',
  });

  // The refusal is on disk, in the file that is meant to be committed.
  const baseline = readBaseline({ runDir });
  assert({
    ok: JSON.stringify(baseline.excluded) === JSON.stringify([REFUSED]),
    message: `${GOVERNANCE_FILE} records excluded ${JSON.stringify(baseline.excluded)}`,
  });
  assert({
    ok: baseline.note.includes('list of NAMES, not a snapshot'),
    message: 'the baseline note does not explain what the deny-list is',
  });

  // And it is stated where the generation is, not left to be found later.
  assert({
    ok: init.stdout.includes(`refused 1 model(s) — ${REFUSED}`),
    message: `the init summary never mentions the refusal:\n${init.stdout}`,
  });

  // THE DEFECT: this used to print 4 proposals and exit 1, forever.
  const sync = runCli({ args: ['sync'], cwd: runDir });

  assert({
    ok: sync.status === 0,
    message: `sync on a narrowed project exited ${sync.status}:\n${sync.stdout}\n${sync.stderr}`,
  });
  assert({
    ok: !sync.stdout.includes('proposal:'),
    message: `sync still proposes the refused model:\n${sync.stdout}`,
  });
  assert({
    ok: sync.stdout.includes(`info: ${REFUSED} is excluded, as recorded in ${GOVERNANCE_FILE}`),
    message: `sync went quiet without saying why:\n${sync.stdout}`,
  });

  // `status` says the same thing, and stays green.
  const status = runCli({ args: ['status'], cwd: runDir });

  assert({
    ok: status.status === 0 && status.stdout.includes(`excluded: 1 model(s) refused — ${REFUSED}`),
    message: `status (exit ${status.status}) does not report the refusal:\n${status.stdout}`,
  });

  return runDir;
};

// ---------------------------------------------------------------------------
// Phase 2 — a name list is not a snapshot
// ---------------------------------------------------------------------------

const phase2 = ({ runDir }) => {
  console.log('── phase 2: a model that appears AFTER the refusal is still loud ──');

  addModel({ runDir });

  const drifted = runCli({ args: ['sync'], cwd: runDir });

  assert({
    ok: drifted.status === 1,
    message: `a genuinely new model did not fail sync (exit ${drifted.status}):\n${drifted.stdout}`,
  });
  assert({
    ok: drifted.stdout.includes('proposal: new model Refund'),
    message: `the new model was silenced:\n${drifted.stdout}`,
  });
  assert({
    ok: !drifted.stdout.includes(`proposal: new model ${REFUSED}`),
    message: `the refused model came back as a proposal:\n${drifted.stdout}`,
  });

  // The report names the refusal door next to `--accept-new`, and picks nothing.
  assert({
    ok:
      drifted.stdout.includes('orangerail sync --exclude <name>[,<name>]') &&
      drifted.stdout.includes('nothing is pre-selected'),
    message: `the report never names the refusal door:\n${drifted.stdout}`,
  });

  // `--accept-new` materializes the new model and STILL not the refused one.
  const accepted = runCli({ args: ['sync', '--accept-new'], cwd: runDir });

  assert({
    ok: existsSync(join(runDir, 'ontology', 'Refund.mjs')),
    message: `--accept-new did not create the new model (exit ${accepted.status}):\n${accepted.stdout}\n${accepted.stderr}`,
  });
  assert({
    ok: !existsSync(join(runDir, 'ontology', `${REFUSED}.mjs`)),
    message: `--accept-new generated the refused model — the exact exposure this ticket prevents`,
  });

  // A recorded name that matches nothing is reported, so it cannot quietly
  // silence a future table that reuses it.
  const pruneDir = prepareRunDir({ name: 'stale' });
  runCli({ args: initFlags({ extra: [`--exclude=${REFUSED}`] }), cwd: pruneDir });
  dropRefusedModel({ runDir: pruneDir });

  const stale = runCli({ args: ['sync'], cwd: pruneDir });

  assert({
    ok: stale.status === 0,
    message: `a stale exclusion failed the run (exit ${stale.status}):\n${stale.stdout}`,
  });
  assert({
    ok: stale.stdout.includes(`recorded exclusion "${REFUSED}" matches nothing in your sources`),
    message: `a stale exclusion was not reported:\n${stale.stdout}`,
  });
};

// ---------------------------------------------------------------------------
// Phase 3 — every refusal, and none of them writes anything
// ---------------------------------------------------------------------------

const phase3 = () => {
  console.log('── phase 3: the refusals ──');

  const unknownDir = prepareRunDir({ name: 'unknown' });
  const unknown = runCli({
    args: initFlags({ extra: ['--exclude=ApiCredentail'] }),
    cwd: unknownDir,
  });

  assert({
    ok: unknown.status !== 0 && `${unknown.stdout}${unknown.stderr}`.includes('in --exclude'),
    message: `a typo'd --exclude was accepted (exit ${unknown.status}):\n${unknown.stdout}\n${unknown.stderr}`,
  });
  assert({
    ok: !existsSync(join(unknownDir, 'orangerail.config.mjs')),
    message: 'a refused init still wrote a config',
  });

  const bothDir = prepareRunDir({ name: 'both' });
  const both = runCli({
    args: initFlags({ extra: ['--models=Customer,Order', `--exclude=Order`] }),
    cwd: bothDir,
  });

  assert({
    ok:
      both.status !== 0 &&
      `${both.stdout}${both.stderr}`.includes('appears in both --models and --exclude'),
    message: `a contradictory selection was resolved by precedence (exit ${both.status}):\n${both.stderr}`,
  });

  const allDir = prepareRunDir({ name: 'all' });
  const all = runCli({
    args: initFlags({ extra: [`--exclude=Customer,Order,${REFUSED}`] }),
    cwd: allDir,
  });

  assert({
    ok: all.status !== 0 && `${all.stdout}${all.stderr}`.includes('every scanned model'),
    message: `an --exclude that leaves nothing to govern was accepted (exit ${all.status}):\n${all.stderr}`,
  });

  // `sync --exclude` with no baseline: there is no honest `recordedBy` to stamp.
  // Narrowed with `--models`, so the table is absent from the ontology and the
  // name is genuinely refusable — the only thing missing is the file to record
  // it in.
  const bareDir = prepareRunDir({ name: 'bare' });
  runCli({ args: initFlags({ extra: ['--models=Customer,Order'] }), cwd: bareDir });
  rmSync(join(bareDir, GOVERNANCE_FILE), { force: true });

  const bare = runCli({ args: ['sync', `--exclude=${REFUSED}`], cwd: bareDir });

  assert({
    ok: bare.status === 2 && bare.stderr.includes('--accept-governance'),
    message: `sync --exclude with no baseline exited ${bare.status}:\n${bare.stdout}\n${bare.stderr}`,
  });
  assert({
    ok: !existsSync(join(bareDir, GOVERNANCE_FILE)),
    message: 'a refused sync --exclude still wrote a baseline',
  });

  // `sync --exclude` naming a model the ontology serves would manufacture the
  // contradiction the check is there to report.
  const servedDir = prepareRunDir({ name: 'served' });
  runCli({ args: initFlags({ extra: [] }), cwd: servedDir });

  const served = runCli({ args: ['sync', `--exclude=${REFUSED}`], cwd: servedDir });

  assert({
    ok: served.status === 2 && served.stderr.includes('already exposes'),
    message: `sync --exclude on a served model exited ${served.status}:\n${served.stdout}\n${served.stderr}`,
  });
  assert({
    ok: readBaseline({ runDir: servedDir }).excluded.length === 0,
    message: 'a refused sync --exclude still recorded the name',
  });
};

const runDir = phase1();
phase2({ runDir });
phase3();

console.log('ONT-059 e2e: all phases passed');
